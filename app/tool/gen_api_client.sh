#!/usr/bin/env bash
# Regenerates app/packages/hearthrise_api from server/openapi.json (Stage 7
# plan D3). Run after `npm run openapi` in server/. Needs Docker and Dart.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
out="$root/app/packages/hearthrise_api"
image="openapitools/openapi-generator-cli:v7.12.0"

rm -rf "$out"
mkdir -p "$out"
# No generated stub tests: the app's api_client_test covers the package.
printf 'test/**\n' > "$out/.openapi-generator-ignore"

docker run --rm -u "$(id -u):$(id -g)" -v "$root:/local" "$image" generate \
  -i /local/server/openapi.json \
  -g dart-dio \
  -o /local/app/packages/hearthrise_api \
  --additional-properties=pubName=hearthrise_api,pubVersion=0.7.0,pubDescription="Generated client for the Hearthrise API.",serializationLibrary=json_serializable

# Current json_serializable writes null-aware elements (Dart 3.8); the
# generator's template still says 3.5. The homepage line is a placeholder.
sed -i.bak -e "s/sdk: '>=3.5.0 <4.0.0'/sdk: ^3.8.0/" -e '/^homepage:/d' "$out/pubspec.yaml"
rm "$out/pubspec.yaml.bak"
# A row's columns can be null; the generator maps `additionalProperties: {}`
# to a map of non-null Objects.
for model in change_dto pulled_change_dto; do
  sed -i.bak 's/Map<String, Object>? row;/Map<String, Object?>? row;/' "$out/lib/src/model/$model.dart"
  rm "$out/lib/src/model/$model.dart.bak"
  grep -q 'Map<String, Object?>? row;' "$out/lib/src/model/$model.dart"
done

(cd "$out" && dart pub get >/dev/null && dart run build_runner build --delete-conflicting-outputs)

hash="$(shasum -a 256 "$root/server/openapi.json" | cut -d' ' -f1)"
cat > "$out/lib/spec_hash.dart" <<EOF
// Generated by app/tool/gen_api_client.sh from server/openapi.json; do not
// edit. api_client_test.dart fails when the spec changes and this package
// was not regenerated (Stage 7 plan D3).
const kOpenApiSha256 = '$hash';
EOF
echo "generated $out ($hash)"
